CREATE OR REPLACE VIEW "public"."user_conversations" AS
 WITH "conversation_pairs" AS (
         SELECT LEAST("direct_messages"."sender_id", "direct_messages"."recipient_id") AS "user1",
            GREATEST("direct_messages"."sender_id", "direct_messages"."recipient_id") AS "user2"
           FROM "public"."direct_messages"
          GROUP BY LEAST("direct_messages"."sender_id", "direct_messages"."recipient_id"), GREATEST("direct_messages"."sender_id", "direct_messages"."recipient_id")
        ), "latest_messages" AS (
         SELECT LEAST("direct_messages"."sender_id", "direct_messages"."recipient_id") AS "user1",
            GREATEST("direct_messages"."sender_id", "direct_messages"."recipient_id") AS "user2",
            "max"("direct_messages"."created_at") AS "latest_message_at"
           FROM "public"."direct_messages"
          GROUP BY LEAST("direct_messages"."sender_id", "direct_messages"."recipient_id"), GREATEST("direct_messages"."sender_id", "direct_messages"."recipient_id")
        )
 SELECT "cp"."user1",
    "cp"."user2",
    "lm"."latest_message_at",
    ( SELECT "dm"."id"
           FROM "public"."direct_messages" "dm"
          WHERE (((("dm"."sender_id" = "cp"."user1") AND ("dm"."recipient_id" = "cp"."user2")) OR (("dm"."sender_id" = "cp"."user2") AND ("dm"."recipient_id" = "cp"."user1"))) AND ("dm"."created_at" = "lm"."latest_message_at"))
         LIMIT 1) AS "latest_message_id",
    ( SELECT "jsonb_build_object"('id', "dm"."id", 'sender_id', "dm"."sender_id", 'content', "dm"."content", 'created_at', "dm"."created_at", 'images', "dm"."images") AS "jsonb_build_object"
           FROM "public"."direct_messages" "dm"
          WHERE (((("dm"."sender_id" = "cp"."user1") AND ("dm"."recipient_id" = "cp"."user2")) OR (("dm"."sender_id" = "cp"."user2") AND ("dm"."recipient_id" = "cp"."user1"))) AND ("dm"."created_at" = "lm"."latest_message_at"))
         LIMIT 1) AS "latest_message",
    ( SELECT "count"(*) AS "count"
           FROM "public"."direct_messages" "dm"
          WHERE (("dm"."recipient_id" = "cp"."user1") AND ("dm"."sender_id" = "cp"."user2") AND ("dm"."read_at" IS NULL))) AS "unread_count_user1",
    ( SELECT "count"(*) AS "count"
           FROM "public"."direct_messages" "dm"
          WHERE (("dm"."recipient_id" = "cp"."user2") AND ("dm"."sender_id" = "cp"."user1") AND ("dm"."read_at" IS NULL))) AS "unread_count_user2"
   FROM ("conversation_pairs" "cp"
     JOIN "latest_messages" "lm" ON ((("cp"."user1" = "lm"."user1") AND ("cp"."user2" = "lm"."user2"))));


