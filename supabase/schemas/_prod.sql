CREATE OR REPLACE FUNCTION "public"."add_reply_to_thread"("p_thread_id" bigint, "p_content" "text", "p_auth0_id" "text", "p_author" "text") RETURNS "json"
    LANGUAGE "plpgsql" SECURITY DEFINER
    AS $$
DECLARE
    v_reply forum_messages;
    v_category text;
BEGIN
    -- Get the category from the parent thread
    SELECT category INTO v_category
    FROM forum_messages
    WHERE id = p_thread_id;

    -- Insert the reply with the same category as the parent
    INSERT INTO forum_messages (
        content,
        auth0_id,
        author,
        parent_id,
        category,
        is_thread_starter
    ) VALUES (
        p_content,
        p_auth0_id,
        p_author,
        p_thread_id,
        v_category,
        false
    )
    RETURNING * INTO v_reply;

    -- Update the thread's reply count and last_reply_at
    UPDATE forum_messages
    SET 
        reply_count = reply_count + 1,
        last_reply_at = NOW()
    WHERE id = p_thread_id;

    RETURN row_to_json(v_reply);
END;
$$;


