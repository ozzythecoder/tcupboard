CREATE OR REPLACE FUNCTION "public"."delete_thread_reactions"("thread_id" bigint) RETURNS "void"
    LANGUAGE "plpgsql" SECURITY DEFINER
    AS $$
BEGIN
  -- Delete reactions to the main thread
  DELETE FROM user_reactions WHERE post_id = thread_id;
  
  -- Delete reactions to all replies in the thread
  DELETE FROM user_reactions 
  WHERE post_id IN (
    SELECT id FROM forum_messages WHERE parent_id = thread_id
  );
END;
$$;


